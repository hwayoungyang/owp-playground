export const chartCatalog = chartCategories.flatMap(({ id }) => {
  const order = new Map<string, number>(
    chartEntryOrder[id].map((exampleId, index) => [exampleId, index]),
  );
  return chartEntries
    .filter((example) => example.category === id)
    .sort(
      (left, right) =>
        (order.get(left.id) ?? Number.MAX_SAFE_INTEGER) -
          (order.get(right.id) ?? Number.MAX_SAFE_INTEGER) || left.id.localeCompare(right.id, 'en'),
    );
});

export type ChartCatalogEntry = (typeof chartCatalog)[number];
const chartDefaults: ReadonlyMap<string, (typeof chartDefaultCatalog)[number]> = new Map(
  chartDefaultCatalog.map((entry) => [entry.id, entry]),
);
export const chartExecutionCatalog = [
  ...chartCatalog.map((entry) => chartDefaults.get(entry.id) ?? entry),
  ...chartVariantCatalog,
];
export type ChartExample = Extract<
  (typeof chartExecutionCatalog)[number],
  { readonly kind: 'chart' }
>;
const chartAliases = new Map([
  ...Object.entries(chartConsolidations),
  ['doughnut-empty', 'doughnut'],
  ['scriptable-pie', 'doughnut'],
  ['linear-gradient', 'line'],
  ['radial-gradient', 'doughnut'],
  ['integer-axis', 'axis-range'],
  ['decimal-axis', 'axis-range'],
  ['long-labels', 'bar'],
  ['animation-progress', 'line'],
  ['animation-delay', 'bar'],
  ['animation-drop', 'bar'],
  ['animation-loop', 'line'],
  ['progressive-line', 'line'],
  ['progressive-easing', 'line'],
]);
export function findChartEntry(id: string | null): ChartCatalogEntry {
  const canonicalId = id ? (chartAliases.get(id) ?? id) : id;
  return chartCatalog.find((example) => example.id === canonicalId) ?? baseChartCatalog[0];
}
